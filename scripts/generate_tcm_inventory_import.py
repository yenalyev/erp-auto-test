def case(
    test_id: str,
    feature_id: str,
    ac_id: str,
    title: str,
    description: str,
    *,
    priority: str = "HIGH",
    severity: str = "MAJOR",
    preconditions: str = "",
    expected_result: str = "",
    tags: str = "inventory,manual",
    role_name: str = ROLE_ADMIN,
    layer: str | None = None,
    automation_test_id: str | None = None,
    steps: list[tuple[str, str]],
    cross: list[str] | None = None,
) -> Case:
    return Case(
        test_id=test_id,
        feature_id=feature_id,
        ac_id=ac_id,
        title=title,
        description=description,
        priority=priority,
        severity=severity,
        preconditions=preconditions,
        expected_result=expected_result,
        tags=tags,
        role_name=role_name,
        automation_layer=layer,
        automation_test_id=automation_test_id,
        cross_features=cross or ["inventory"],
        steps=[Step(i + 1, a, e) for i, (a, e) in enumerate(steps)],
    )


